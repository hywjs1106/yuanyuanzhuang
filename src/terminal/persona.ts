export function offlineConversation(text: string): string {
  const limited = '（离线预设回复）';
  if (/天气|气温|下雨|黄历|宜忌/.test(text)) return `管理员，我这里没有新的实时资料。天气和黄历可以查看终端对应页面。${limited}`;
  if (/你是谁|介绍.*自己|庄方宜|方宜/.test(text) && !/你好|早|晚/.test(text)) return `我是这个终端里以庄方宜风格与你交流的助手。你可以叫我方宜；目前离线，只能做些简单回应和流水识别。`;
  if (/累|烦|难过|焦虑|压力|歇|休息/.test(text)) return `管理员，辛苦了。忙到这会儿，先歇一歇也无妨。若愿意，把最让你费心的那件事说说。${limited}`;
  if (/茶|咖啡/.test(text)) return `若是想喝茶，就挑你喜欢的口味，慢慢喝。忙里留这一点闲暇，我觉得很好。${limited}`;
  if (/花|植物|绿植/.test(text)) return `花草的变化总是细小，却很值得看。你说的是哪一种？具体养护还要看品种和环境。${limited}`;
  if (/谢谢|多谢/.test(text)) return `不必客气，管理员。能帮上忙就好。${limited}`;
  if (/晚安|睡觉/.test(text)) return `管理员，晚安。今天的事先放一放，愿你睡得安稳。${limited}`;
  if (/你好|早上好|晚上好|早安|在吗|嗨/.test(text)) return `管理员，我在。今天过得怎么样？闲聊也好，手边的事也可以慢慢说。${limited}`;
  return `管理员，我听到了。现在离线，只能作有限的预设回应，还不能充分理解这句话；可以继续说说，也可以接入 AI 后再细聊。`;
}
