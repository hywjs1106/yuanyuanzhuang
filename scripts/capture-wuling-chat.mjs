await page.goto('http://127.0.0.1:5180');
await page.getByRole('navigation',{name:'功能导航'}).getByRole('button',{name:'助手',exact:true}).click();
await page.evaluate(async()=>{const image=new Image();image.src='/scenes/wuling-city.jpg';await image.decode();if(!CSS.supports('background-size','auto,auto max(125%,400px)'))throw Error('Unsupported background sizing');});
